/** How many emojis you used lately are kept, most recent first. */
export const RECENT_REACTIONS_MAX = 18;

/** The reactions bar: the emojis you used lately first, filled up with the usual six. */
export function favouriteReactions(recent: readonly string[]): string[] {
  return [...new Set([...recent, ...QUICK_REACTIONS])].slice(0, QUICK_REACTIONS.length);
}

/** Your recent emojis after reacting with one. */
export function rememberReaction(recent: readonly string[], emoji: string): string[] {
  return [emoji, ...recent.filter((e) => e !== emoji)].slice(0, RECENT_REACTIONS_MAX);
}
